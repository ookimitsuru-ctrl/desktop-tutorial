// 文字→ポリライン座標配列へ前処理
const GLYPHS = {};
for (const k in G) {
  GLYPHS[k] = G[k].map((s) => {
    const pts = [];
    for (let i = 0; i + 1 < s.length; i += 2) pts.push([+s[i], +s[i + 1]]);
    return pts;
  });
}

export const ADV = 5.3 / 6; // 高さ=1 としたときの文字送り

export function textWidth(str, size) {
  return str.length * ADV * size - (ADV - 4 / 6) * size;
}

// size: 文字の高さ (HUD単位), (x,y): 文字列の中心高さ, align: 'l' | 'c' | 'r'
export function drawText(g, str, x, y, size, r, gc, b, w = 2, a = 1, align = 'l', italic = 0) {
  str = String(str).toUpperCase();
  if (size < 0.042) size = 0.042;
  const s = size / 6;
  let ox = x;
  const tw = textWidth(str, size);
  if (align === 'c') ox = x - tw / 2; else if (align === 'r') ox = x - tw;
  const y0 = y - size / 2;
  for (let i = 0; i < str.length; i++) {
    const gl = GLYPHS[str[i]] || GLYPHS[str[i].toLowerCase()];
    if (gl) {
      for (let si = 0; si < gl.length; si++) {
        const st = gl[si];
        for (let p = 0; p + 1 < st.length; p++) {
          g.line2(
            ox + (st[p][0] + st[p][1] * italic) * s, y0 + st[p][1] * s,
            ox + (st[p + 1][0] + st[p + 1][1] * italic) * s, y0 + st[p + 1][1] * s,
            r, gc, b, w, a);
        }
        if (st.length === 2 && st[0][0] === st[1][0] && st[0][1] + 1 === st[1][1] && false) { /* noop */ }
      }
    }
    ox += ADV * size;
  }
}
